// Dev tool: builds src/config/wada-palettes.js from the open dataset of
// Sanzo Wada's "A Dictionary of Color Combinations" (1933), published as
// the MIT-licensed package dictionary-of-colour-combinations by Matt DesLauriers.
// Usage: node scripts/wada-palettes.mjs path/to/colors.json
import { readFileSync, writeFileSync } from 'node:fs';

const colors = JSON.parse(readFileSync(process.argv[2], 'utf8'));
const combos = new Map();
for (const c of colors) {
    for (const id of c.combinations) {
        if (!combos.has(id)) combos.set(id, []);
        combos.get(id).push({ name: c.name, hex: c.hex, l: c.lab[0] });
    }
}
const out = [...combos.entries()]
    .sort((a, b) => a[0] - b[0])
    .map(([id, cs]) => ({ id, colors: cs.map((c) => [c.name, c.hex, Math.round(c.l)]) }));
const body = `// Generated by scripts/wada-palettes.mjs. Do not edit by hand.
// Colour combinations from Sanzo Wada, "A Dictionary of Color Combinations"
// (1933), via the MIT-licensed dataset dictionary-of-colour-combinations
// (c) Matt DesLauriers. Each colour is [name, hex, CIE L lightness 0 to 100].
export const WADA_COMBINATIONS = ${JSON.stringify(out)};
`;
writeFileSync(new URL('../src/config/wada-palettes.js', import.meta.url), body);
console.log(out.length, 'combinations');
